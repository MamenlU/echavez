import fs from 'node:fs';
import path from 'node:path';

const [, , inputPath, outputPath] = process.argv;
const schemaOnly = process.argv.includes('--schema-only');

if (!inputPath || !outputPath) {
  console.error('Usage: node scripts/convert-mysql-dump-to-postgres.mjs <input.sql> <output.sql>');
  process.exit(1);
}

const source = fs.readFileSync(inputPath, 'utf8').replace(/^\uFEFF/, '');

function splitSqlStatements(sql) {
  const statements = [];
  let current = '';
  let inString = false;
  let escaped = false;

  for (const char of sql) {
    current += char;
    if (inString) {
      if (escaped) {
        escaped = false;
      } else if (char === '\\') {
        escaped = true;
      } else if (char === "'") {
        inString = false;
      }
    } else if (char === "'") {
      inString = true;
    } else if (char === ';') {
      statements.push(current.trim());
      current = '';
    }
  }

  if (current.trim()) statements.push(current.trim());
  return statements;
}

function splitClauses(value) {
  const clauses = [];
  let current = '';
  let depth = 0;
  let inString = false;

  for (let i = 0; i < value.length; i += 1) {
    const char = value[i];
    if (inString) {
      current += char;
      if (char === '\\' && i + 1 < value.length) {
        current += value[++i];
      } else if (char === "'") {
        inString = false;
      }
      continue;
    }
    if (char === "'") inString = true;
    if (char === '(') depth += 1;
    if (char === ')') depth -= 1;
    if (char === ',' && depth === 0) {
      clauses.push(current.trim());
      current = '';
    } else {
      current += char;
    }
  }
  if (current.trim()) clauses.push(current.trim());
  return clauses;
}

function postgresStringLiterals(sql) {
  let output = '';
  for (let i = 0; i < sql.length; i += 1) {
    if (sql[i] !== "'") {
      output += sql[i];
      continue;
    }

    let value = '';
    i += 1;
    for (; i < sql.length; i += 1) {
      const char = sql[i];
      if (char === "'") break;
      if (char !== '\\' || i + 1 >= sql.length) {
        value += char;
        continue;
      }

      const escaped = sql[++i];
      const replacements = {
        '0': '',
        b: '\b',
        n: '\n',
        r: '\r',
        t: '\t',
        Z: '\x1a',
        "'": "'",
        '"': '"',
        '\\': '\\',
      };
      value += Object.hasOwn(replacements, escaped) ? replacements[escaped] : escaped;
    }
    output += `'${value.replaceAll("'", "''")}'`;
  }
  return output;
}

function cleanIdentifiers(sql) {
  return sql.replace(/`([^`]+)`/g, '$1');
}

const cleaned = source
  .replace(/\/\*![\s\S]*?\*\//g, '')
  .split(/\r?\n/)
  .filter((line) => !line.trimStart().startsWith('--'))
  .join('\n');

const statements = splitSqlStatements(cleaned);
const identityColumns = new Map();
const updateTimestampTables = new Set();

for (const statement of statements) {
  const identity = statement.match(
    /^ALTER TABLE\s+`([^`]+)`\s+MODIFY\s+`([^`]+)`\s+(bigint|int)/i,
  );
  if (identity && /AUTO_INCREMENT/i.test(statement)) {
    identityColumns.set(`${identity[1]}.${identity[2]}`, identity[3].toLowerCase());
  }

  const create = statement.match(/^CREATE TABLE\s+`([^`]+)`/i);
  if (create && /ON UPDATE\s+current_timestamp\(\)/i.test(statement)) {
    updateTimestampTables.add(create[1]);
  }
}

const createStatements = [];
const dataStatements = [];
const keyStatements = [];
const indexStatements = [];
const foreignKeyStatements = [];

for (const rawStatement of statements) {
  const statement = rawStatement.trim();
  if (!statement) continue;

  if (/^CREATE TABLE/i.test(statement)) {
    const table = statement.match(/^CREATE TABLE\s+`([^`]+)`/i)?.[1];
    let converted = cleanIdentifiers(statement)
      .replace(/\b(bigint|int|smallint|tinyint)\(\d+\)/gi, (_, type) => {
        const mapped = { int: 'integer', tinyint: 'smallint' };
        return mapped[type.toLowerCase()] || type.toLowerCase();
      })
      .replace(/\bUNSIGNED\b/gi, '')
      .replace(/\bmediumtext\b|\blongtext\b/gi, 'text')
      .replace(/\bdatetime\b/gi, 'timestamp')
      .replace(/\benum\((?:'[^']*'\s*,?\s*)+\)/gi, 'text')
      .replace(/\s+ON UPDATE\s+current_timestamp\(\)/gi, '')
      .replace(/current_timestamp\(\)/gi, 'CURRENT_TIMESTAMP')
      .replace(/\)\s+ENGINE=[\s\S]*$/i, ')');

    for (const [key, mysqlType] of identityColumns) {
      const [identityTable, column] = key.split('.');
      if (identityTable !== table) continue;
      const pgType = mysqlType === 'bigint' ? 'bigint' : 'integer';
      const columnPattern = new RegExp(`(^\\s*${column}\\s+)${pgType}(?=\\s)`, 'mi');
      converted = converted.replace(
        columnPattern,
        `$1${pgType} GENERATED BY DEFAULT AS IDENTITY`,
      );
    }

    createStatements.push(`${converted};`);
    continue;
  }

  if (/^INSERT INTO/i.test(statement)) {
    dataStatements.push(`${cleanIdentifiers(postgresStringLiterals(statement))};`);
    continue;
  }

  const alter = statement.match(/^ALTER TABLE\s+`([^`]+)`\s+([\s\S]+);?$/i);
  if (!alter) continue;
  const table = alter[1];
  const body = alter[2].replace(/;$/, '').trim();

  for (const rawClause of splitClauses(body)) {
    const clause = cleanIdentifiers(rawClause);
    if (/^MODIFY\s+/i.test(clause)) continue;

    const primary = clause.match(/^ADD PRIMARY KEY\s*(\([\s\S]+\))$/i);
    if (primary) {
      keyStatements.push(`ALTER TABLE ${table} ADD CONSTRAINT ${table}_pkey PRIMARY KEY ${primary[1]};`);
      continue;
    }

    const unique = clause.match(/^ADD UNIQUE KEY\s+(\S+)\s*(\([\s\S]+\))$/i);
    if (unique) {
      keyStatements.push(
        `ALTER TABLE ${table} ADD CONSTRAINT ${table}_${unique[1]} UNIQUE ${unique[2]};`,
      );
      continue;
    }

    const index = clause.match(/^ADD KEY\s+(\S+)\s*(\([\s\S]+\))$/i);
    if (index) {
      indexStatements.push(`CREATE INDEX ${table}_${index[1]} ON ${table} ${index[2]};`);
      continue;
    }

    const foreign = clause.match(/^ADD CONSTRAINT\s+(\S+)\s+([\s\S]+)$/i);
    if (foreign) {
      foreignKeyStatements.push(
        `ALTER TABLE ${table} ADD CONSTRAINT ${table}_${foreign[1]} ${foreign[2]};`,
      );
    }
  }
}

const sequenceStatements = [...identityColumns].map(([key]) => {
  const [table, column] = key.split('.');
  return `SELECT setval(pg_get_serial_sequence('${table}', '${column}'), COALESCE(MAX(${column}), 1), MAX(${column}) IS NOT NULL) FROM ${table};`;
});

const triggerStatements = updateTimestampTables.size
  ? [
      `CREATE OR REPLACE FUNCTION set_updated_at()\nRETURNS trigger\nLANGUAGE plpgsql\nAS $$\nBEGIN\n  NEW.updated_at = CURRENT_TIMESTAMP;\n  RETURN NEW;\nEND;\n$$;`,
      ...[...updateTimestampTables].flatMap((table) => [
        `DROP TRIGGER IF EXISTS ${table}_set_updated_at ON ${table};`,
        `CREATE TRIGGER ${table}_set_updated_at BEFORE UPDATE ON ${table}\nFOR EACH ROW EXECUTE FUNCTION set_updated_at();`,
      ]),
    ]
  : [];

const output = [
  '-- Generated from a MariaDB/phpMyAdmin dump by scripts/convert-mysql-dump-to-postgres.mjs',
  '-- Source data and identifiers are preserved; MySQL ENUM columns are represented as text.',
  'BEGIN;',
  "SET client_encoding = 'UTF8';",
  ...createStatements,
  ...keyStatements,
  ...(!schemaOnly ? dataStatements : []),
  ...(!schemaOnly ? sequenceStatements : []),
  ...foreignKeyStatements,
  ...indexStatements,
  ...triggerStatements,
  'COMMIT;',
].join('\n\n') + '\n';

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output, 'utf8');

console.log(
  `Converted ${createStatements.length} tables, ${schemaOnly ? 0 : dataStatements.length} data batches, ` +
    `${foreignKeyStatements.length} foreign keys, and ${indexStatements.length} indexes.`,
);
